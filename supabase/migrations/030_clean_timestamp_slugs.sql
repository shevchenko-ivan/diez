-- Timestamp slugs read as machine-generated duplicates to crawlers and were a
-- suspected driver of GSC «Crawled — currently not indexed». The redirects
-- table keeps every old URL alive: the song page consults it on a miss and
-- issues a 308 (see getSongSlugRedirect + app/songs/[slug]/page.tsx, deployed
-- BEFORE this migration runs so there is no 404 window).

