  old_slug text primary key,
  new_slug text not null,
  created_at timestamptz not null default now()
);
alter table public.slug_redirects enable row level security;
drop policy if exists "slug_redirects_read_all" on public.slug_redirects;
create policy "slug_redirects_read_all" on public.slug_redirects for select using (true);

